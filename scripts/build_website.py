"""Bundle the project's outputs into the static website.

    python scripts/build_website.py

1. copies every figure from reports/figures -> website/assets/img
2. renders every notebook in notebooks/ to standalone HTML -> website/notebooks
3. copies the .ipynb files so visitors can download them
4. bundles website/assets/data/*.json into website/assets/js/data.js
   (so index.html also works when opened directly from disk, without a server)
"""
import json
import shutil
from pathlib import Path

import nbformat
from nbconvert import HTMLExporter

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "website"
IMG, NB_OUT, DATA = WEB / "assets" / "img", WEB / "notebooks", WEB / "assets" / "data"

for d in (IMG, NB_OUT, DATA):
    d.mkdir(parents=True, exist_ok=True)

# 1. figures
n_fig = 0
for f in sorted((ROOT / "reports" / "figures").glob("*.png")):
    shutil.copy2(f, IMG / f.name)
    n_fig += 1

# 2-3. notebooks
exporter = HTMLExporter(template_name="lab")
notebooks = []
for nb_path in sorted((ROOT / "notebooks").glob("*.ipynb")):
    nb = nbformat.read(nb_path, as_version=4)
    body, _ = exporter.from_notebook_node(nb)
    (NB_OUT / f"{nb_path.stem}.html").write_text(body, encoding="utf-8")
    shutil.copy2(nb_path, NB_OUT / nb_path.name)
    title = next((c.source.splitlines()[0].lstrip("# ").strip() for c in nb.cells if c.cell_type == "markdown"), nb_path.stem)
    notebooks.append({"file": nb_path.stem, "title": title,
                      "cells": len(nb.cells), "code_cells": sum(c.cell_type == "code" for c in nb.cells)})

# 4. data bundle
bundle = {p.stem: json.loads(p.read_text()) for p in sorted(DATA.glob("*.json"))}
bundle["notebooks"] = notebooks
bundle["figures"] = sorted(p.name for p in IMG.glob("*.png"))
(WEB / "assets" / "js" / "data.js").write_text(
    "// Generated by scripts/build_website.py. Do not edit by hand.\nwindow.NEURO_DATA = " + json.dumps(bundle) + ";\n",
    encoding="utf-8")

print(f"figures: {n_fig} | notebooks: {len(notebooks)} | data keys: {list(bundle)}")
